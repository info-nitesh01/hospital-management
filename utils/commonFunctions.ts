/**
 * Format a number as currency with appropriate suffix (B for billions, M for millions, K for thousands)
 * @param value - The number to format
 * @returns Formatted string like "$2.5B", "$500M", or "$50K"
 */
export const formatCurrency = (value: number): string => {
  if (value >= 1e9) return `$${(value / 1e9).toFixed(1)}B`;
  if (value >= 1e6) return `$${(value / 1e6).toFixed(1)}M`;
  if (value >= 1e3) return `$${(value / 1e3).toFixed(1)}K`;
  return `$${value.toFixed(0)}`;
};

/**
 * Format a number with thousand separators
 * @param value - The number to format
 * @returns Formatted string like "1,234,567"
 */
export const formatNumber = (value: number): string => {
  return value.toLocaleString();
};

/**
 * Format amount for display in charts and lists
 * Used for condensed display where space is limited
 * @param amount - The number to format
 * @returns Formatted string like "$1.5M", "$426.9K", etc.
 */
export const formatAmount = (amount: number): string => {
  if (amount >= 1000000) {
    return `$${(amount / 1000000).toFixed(1)}M`;
  } else if (amount >= 1000) {
    return `$${(amount / 1000).toFixed(1)}K`;
  }
  return formatCurrency(amount);
};

